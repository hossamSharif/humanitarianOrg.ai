/**
 * Regenerates src/types.ts from the database schema with the Supabase CLI.
 *
 *   pnpm --filter @ngo/database gen:types                        # local stack (supabase start)
 *   SUPABASE_PROJECT_ID=<ref> pnpm --filter @ngo/database gen:types   # cloud project
 *
 * The cloud form needs `npx supabase login` (or SUPABASE_ACCESS_TOKEN). When Supabase MCP is
 * configured, `generate_typescript_types` produces the same output (research R20).
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER =
  '// Generated by `pnpm --filter @ngo/database gen:types` (Supabase type generation). Do not edit.\n\n';

const outFile = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/types.ts');
const projectId = process.env.SUPABASE_PROJECT_ID;
const target = projectId ? ['--project-id', projectId] : ['--local'];

const types = execFileSync(
  'npx',
  ['-y', 'supabase@2', 'gen', 'types', 'typescript', ...target, '--schema', 'public'],
  { encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 16 * 1024 * 1024 }
);

writeFileSync(outFile, HEADER + types.replace(/\r\n/g, '\n'));
console.log(`wrote ${path.relative(process.cwd(), outFile)}`);
